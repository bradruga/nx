namespace Nx.Components;

/// <summary>Where an <see cref="NxChart"/>'s legend sits.</summary>
public enum NxChartLegendPosition
{
    /// <summary>Under the chart.</summary>
    Bottom,

    /// <summary>Beside the chart, on the right; under it when the chart is narrow.</summary>
    Right,

    /// <summary>Above the chart.</summary>
    Top,

    /// <summary>No legend.</summary>
    None
}
