namespace Nx.Components;

/// <summary>Height and padding of an <see cref="NxButton"/>. Set via <see cref="NxButton.Size"/>.</summary>
public enum NxButtonSize
{
    /// <summary><c>--nx-control-height-sm</c> (28px).</summary>
    Small,

    /// <summary><c>--nx-control-height-md</c> (34px). Default; matches <c>NxTextBox</c>.</summary>
    Medium,

    /// <summary><c>--nx-control-height-lg</c> (42px).</summary>
    Large
}
